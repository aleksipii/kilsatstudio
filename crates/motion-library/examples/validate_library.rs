//! Validate an asset pack's library.
//!
//! `validate_library <pack_root> [--distribution] [--preview-svg <dir>]`
//!
//! Prints counts per kind, the total anchor count (declared anchors plus
//! generated room anchors), warnings, and assembles every location × variant
//! and every set. Exits non-zero on any error. `--preview-svg` writes a flat
//! SVG sketch of each assembly (art layers plus anchors and marks in red) for
//! authoring review; it is not the production renderer.
use motion_art::{Color, Content};
use motion_library::{assemble_location, assemble_set, Anchor, Assembled, Kind, Library, Policy};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

fn rgba(c: &Color) -> String {
    format!(
        "rgba({},{},{},{:.3})",
        c.r,
        c.g,
        c.b,
        f64::from(c.a) / 255.0
    )
}

fn preview(dir: &Path, name: &str, a: &Assembled) -> std::io::Result<()> {
    let mut s = String::from(
        "<svg xmlns='http://www.w3.org/2000/svg' width='1920' height='1080' viewBox='0 0 1920 1080'>",
    );
    for l in &a.document.layers {
        let _ = match &l.content {
            Content::Rectangle { rect: r, color } => write!(
                s,
                "<rect x='{}' y='{}' width='{}' height='{}' fill='{}'/>",
                r.x,
                r.y,
                r.width,
                r.height,
                rgba(color)
            ),
            Content::Ellipse { rect: r, color } => write!(
                s,
                "<ellipse cx='{}' cy='{}' rx='{}' ry='{}' fill='{}'/>",
                r.x + r.width / 2.0,
                r.y + r.height / 2.0,
                r.width / 2.0,
                r.height / 2.0,
                rgba(color)
            ),
            Content::Stroke {
                points,
                color,
                width,
            } => {
                let pts: Vec<String> = points.iter().map(|p| format!("{},{}", p.x, p.y)).collect();
                write!(
                    s,
                    "<polyline points='{}' fill='none' stroke='{}' stroke-width='{}' stroke-linecap='round' stroke-linejoin='round'/>",
                    pts.join(" "),
                    rgba(color),
                    width
                )
            }
            _ => Ok(()),
        };
    }
    for w in &a.anchors {
        let p = w.anchor.reference_point();
        let _ = match &w.anchor {
            Anchor::Ground { at, width, .. } => write!(
                s,
                "<line x1='{}' y1='{}' x2='{}' y2='{}' stroke='red' stroke-width='2' stroke-dasharray='8 6'/>",
                at.x, at.y, at.x + width, at.y
            ),
            Anchor::Doorway { rect: r, .. } | Anchor::Screen { rect: r, .. } => write!(
                s,
                "<rect x='{}' y='{}' width='{}' height='{}' fill='none' stroke='red' stroke-width='2'/>",
                r.x, r.y, r.width, r.height
            ),
            _ => write!(s, "<circle cx='{}' cy='{}' r='6' fill='red'/>", p.x, p.y),
        };
    }
    for m in &a.marks {
        let _ = write!(
            s,
            "<circle cx='{}' cy='{}' r='12' fill='none' stroke='blue' stroke-width='3'/>",
            m.at.x, m.at.y
        );
    }
    s.push_str("</svg>");
    std::fs::write(dir.join(format!("{name}.svg")), s)
}

fn main() -> ExitCode {
    let mut root: Option<PathBuf> = None;
    let mut policy = Policy::Authoring;
    let mut preview_dir: Option<PathBuf> = None;
    let mut args = std::env::args_os().skip(1);
    while let Some(arg) = args.next() {
        if arg == "--distribution" {
            policy = Policy::Distribution;
        } else if arg == "--preview-svg" {
            preview_dir = args.next().map(PathBuf::from);
        } else if root.is_none() {
            root = Some(PathBuf::from(arg));
        } else {
            eprintln!("usage: validate_library <pack_root> [--distribution] [--preview-svg <dir>]");
            return ExitCode::from(2);
        }
    }
    let Some(root) = root else {
        eprintln!("usage: validate_library <pack_root> [--distribution] [--preview-svg <dir>]");
        return ExitCode::from(2);
    };
    let (lib, warnings) = match Library::load(&root, policy) {
        Ok(v) => v,
        Err(e) => {
            eprintln!("error: {e}");
            return ExitCode::FAILURE;
        }
    };
    for kind in Kind::ALL {
        println!("{:<11} {}", kind.directory(), lib.count(kind));
    }
    let declared: usize = lib.iter().map(|m| m.anchors.len()).sum();
    let generated: usize = lib
        .iter()
        .filter_map(|m| m.room_art())
        .map(|r| r.anchors.len())
        .sum();
    println!(
        "anchors     {} ({declared} declared, {generated} generated by rooms)",
        declared + generated
    );
    let mut failures = 0;
    let mut assembled = 0;
    for m in lib.iter() {
        let result = match m.kind {
            Kind::Location => std::iter::once(None)
                .chain(m.variants.iter().map(|v| Some(v.name.as_str())))
                .try_for_each(|v| {
                    assembled += 1;
                    let a = assemble_location(&lib, &m.id, v, "scene")?;
                    if let Some(dir) = &preview_dir {
                        let name =
                            format!("{}{}", m.id, v.map(|v| format!("@{v}")).unwrap_or_default());
                        if let Err(e) = preview(dir, &name, &a) {
                            eprintln!("warning: preview {name}: {e}");
                        }
                    }
                    Ok(())
                }),
            Kind::Set => {
                assembled += 1;
                assemble_set(&lib, &m.id, None, "scene").map(|a| {
                    if let Some(dir) = &preview_dir {
                        if let Err(e) = preview(dir, &m.id, &a) {
                            eprintln!("warning: preview {}: {e}", m.id);
                        }
                    }
                })
            }
            _ => Ok(()),
        };
        if let Err(e) = result {
            eprintln!("error: assemble {}: {e}", m.id);
            failures += 1;
        }
    }
    println!("assembled   {assembled} (locations × variants, sets)");
    for w in &warnings {
        println!("warning: {}: {}: {}", w.file.display(), w.id, w.message);
    }
    println!("warnings    {}", warnings.len());
    if failures > 0 {
        ExitCode::FAILURE
    } else {
        ExitCode::SUCCESS
    }
}
